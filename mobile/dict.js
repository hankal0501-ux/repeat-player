function isJapanese(text){return /[぀-ゟ゠-ヿ]/.test(text);}
function isChinese(text){return /[一-鿿]/.test(text) && !isJapanese(text);}
function isVietnamese(text){return /[ăâđêôơưĂÂĐÊÔƠƯàáạảãằắặẳẵầấậẩẫèéẹẻẽềếệểễìíịỉĩòóọỏõồốộổỗờớợởỡùúụủũừứựửữỳýỵỷỹÀ-Ỹ]/.test(text);}
function isEnglish(text){return /[A-Za-z]/.test(text) && !/[一-鿿぀-ヿ]/.test(text) && !isVietnamese(text);}
function detectLang(text){
  if(isJapanese(text)) return 'ja';
  if(isVietnamese(text)) return 'vi';
  if(isChinese(text)) return 'zh';
  if(isEnglish(text)) return 'en';
  return 'zh';
}
const LANG_LABEL = {ja:'일본어', zh:'중국어', vi:'베트남어', en:'영어'};

function analyzeJapanese(text){
  const words = [];
  let i = 0;
  while(i < text.length){
    let matched = false;
    for(let len = 8; len >= 2; len--){
      if(i + len <= text.length){
        const sub = text.substring(i, i+len);
        if(JP_DICT[sub]){
          words.push({type:'word', text:sub, meaning:JP_DICT[sub]});
          i += len; matched = true; break;
        }
      }
    }
    if(!matched){
      const ch = text[i];
      if(/[一-鿿]/.test(ch)){
        const e = HANJA_DICT[ch];
        words.push({type:'char', text:ch, sound:e?e.s:'', meaning:e?e.m:''});
      } else if(/[ぁ-んァ-ヶ]/.test(ch)){
        let kana = ch, j = i + 1;
        while(j < text.length && /[ぁ-んァ-ヶー]/.test(text[j])){ kana += text[j]; j++; }
        words.push({type:'kana', text:kana, meaning:'(가나)'});
        i = j; continue;
      }
      i++;
    }
  }
  return words;
}

